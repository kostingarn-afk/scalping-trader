-- V6__commission_rate_trader.sql
-- Ставка брокера за сторону: «Инвестор» 0.003 → «Трейдер» 0.0005 (шаг 1.9, to_do.md §4.1).
-- Порог комиссионного фильтра |TP−entry| ≥ ratio × 2 × rate падает с 1.8 % до 0.30 %:
-- при 1.8 % минутные сигналы отсекались почти полностью, торговли не было.
-- V4 не правится (применённые миграции неизменяемы); значение меняется этой миграцией.
-- Абонентская плата «Трейдера» (₽/мес) в расчёте на сделку не моделируется — см. to_do.md §5.1.

UPDATE risk_config
SET value = '0.0005',
    description = 'Ставка брокера за сторону сделки: Инвестор 0.003, Трейдер 0.0005, Премиум 0.0004',
    updated_at = now(),
    updated_by = 'system'
WHERE key = 'commission_rate_per_side';
